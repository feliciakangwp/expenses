// Enrich with category data
export function enrichDemoTransactions(transactions: Transaction[]): Transaction[] {
  return transactions.map((t) => ({
    ...t,
    category: DEMO_CATEGORIES.find((c) => c.id === t.category_id),
    payment_method: DEMO_PAYMENT_METHODS.find((p) => p.id === t.payment_method_id),
  }))
}

